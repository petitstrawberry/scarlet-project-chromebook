//! Normalized render targets keep the existing BGRA backing ABI.
use sgfx_core::ir::TextureFormat;

pub(crate) fn srgb(format: TextureFormat) -> bool {
    matches!(
        format,
        TextureFormat::Bgra8UnormSrgb | TextureFormat::Rgba8UnormSrgb
    )
}

pub(crate) fn fixed_target(format: TextureFormat) -> bool {
    matches!(
        format,
        TextureFormat::Bgra8Unorm
            | TextureFormat::Rgba8Unorm
            | TextureFormat::Bgra8UnormSrgb
            | TextureFormat::Rgba8UnormSrgb
            | TextureFormat::R8Unorm
            | TextureFormat::Rg8Unorm
    )
}

/// Expanded R8 stores logical red in physical byte 3. XYZW maps RGBA
/// to ABGR in memory, preserving upload, sampling and readback conventions.
pub(crate) fn target_swap(alpha_mask: bool, tiled: bool) -> u32 {
    if alpha_mask {
        3
    } else if tiled {
        0
    } else {
        1
    }
}

/// Missing R8/RG8 destination alpha is one, independently of unused backing bytes.
/// The source alpha remains the shader output and still scales source RGB.
pub(crate) fn target_blend(mut control: u32, alpha_mask: bool) -> u32 {
    if alpha_mask {
        for shift in [0, 8, 16, 24] {
            let factor = (control >> shift) & 31;
            let replacement = match factor {
                10 => 1,
                11 => 0,
                _ => factor,
            };
            control = (control & !(31 << shift)) | (replacement << shift);
        }
    }
    control
}

/// Round the sRGB transfer function to UNORM8 without a runtime libm dependency.
/// Threshold n is decode_srgb((n+0.5)/255); binary search takes at most 8 steps.
/// Alpha must use ordinary linear UNORM conversion.
pub(crate) fn srgb8(linear: f32) -> u32 {
    let mut lo = 0;
    let mut hi = SRGB_THRESHOLDS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        if f64::from(linear) < SRGB_THRESHOLDS[mid] {
            hi = mid;
        } else {
            lo = mid + 1;
        }
    }
    lo as u32
}

