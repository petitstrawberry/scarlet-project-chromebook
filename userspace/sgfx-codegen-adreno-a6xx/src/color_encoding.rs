#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn srgb_quantization_matches_transfer_function() {
        for i in 0..=100_000 {
            let x = i as f32 / 100_000.0;
            let x64 = f64::from(x);
            let encoded = if x64 <= 0.0031308 {
                x64 * 12.92
            } else {
                1.055 * x64.powf(1.0 / 2.4) - 0.055
            };
            assert_eq!(srgb8(x), (encoded * 255.0 + 0.5) as u32);
        }
        assert_eq!(srgb8(-1.0), 0);
        assert_eq!(srgb8(2.0), 255);
    }
}
